import assert from 'node:assert/strict';
import test from 'node:test';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
import {runInNewContext} from 'node:vm';
const src=(path:string)=>readFileSync(new URL('../miniprogram/'+path,import.meta.url),'utf8');
test('Mini health navigation mirrors Web while retaining four bottom tabs',()=>{
  const app=JSON.parse(src('app.json'));
  assert.ok(app.pages.includes('pages/health/health'));
  assert.equal(app.tabBar.list.length,4);
  const more=src('pages/more/more.ts');
  assert.match(more,/title:'健康与运动',items:\[\s*\{key:'health',title:'健康'.*?pages\/health\/health/);
  assert.match(more,/title:'家庭生活'/);
  const wxml=src('pages/health/health.wxml');
  assert.match(wxml,/<user-avatar user-id="\{\{item.userId\}\}"/);
  for(const title of ['快速记录','选择指标','健康时间线','健康档案','相关日程与待办','查看原始资料','下载 / 打开原始资料'])assert.ok(wxml.includes(title));
  const page=src('pages/health/health.ts');
  assert.match(page,/label:'概览'.*label:'指标'.*label:'事件'.*label:'档案'/);
  assert.doesNotMatch(page,/wx\.setStorage|setInterval|console\.log/);
  assert.match(page,/limit:12/);
  assert.match(page,/limit:30/);
  assert.match(page,/p\.nextCursor&&!bmi/);
  assert.match(page,/if\(open&&!this\.data\.eventChoices\.length\)/);
});
test('Mini values preserve Web BMI and boolean/date semantics',()=>{
  const code=src('utils/health-values.ts').replace(/^import type .*?;$/m,'').replace(/export function /g,'function ');
  const utils=runInNewContext(stripTypeScriptTypes(code)+'\n({derivedBmi,growthMetrics,healthSince,measurementFields,trendSeries})');
  const h={id:'rec_h',name:'身高',valueType:'number',defaultUnit:'cm',version:1},w={id:'rec_w',name:'体重',valueType:'number',defaultUnit:'kg',version:1};
  const rows=[{id:'rec_1',subjectPersonId:'per_a',metricId:h.id,unit:'cm',observedDate:'2026-01-01',valueNumber:150},{id:'rec_2',subjectPersonId:'per_a',metricId:w.id,unit:'kg',observedDate:'2026-01-01',valueNumber:45}];
  assert.equal(utils.derivedBmi(rows,h.id,w.id,'per_a').value,20);
  assert.equal(utils.derivedBmi(rows,h.id,w.id,'per_a','2026-01-01'),null);
  assert.equal(utils.derivedBmi([...rows,{...rows[0],id:'rec_3'}],h.id,w.id,'per_a'),null);
  assert.equal(utils.growthMetrics([h,w],false).height,undefined);
  assert.equal(utils.measurementFields({...h,valueType:'boolean'},'2026-01-01','false','','').valueBoolean,false);
  assert.equal(utils.measurementFields(h,'2026-01-01','0','cm','').valueNumber,0);
  assert.equal(utils.healthSince('2024-03-01',2),'2024-02-29');
  assert.equal(utils.trendSeries(rows).points.length,0);
  assert.equal(utils.trendSeries([rows[0],{...rows[0],id:'rec_3',observedDate:'2026-01-03',valueNumber:151}]).points.length,2);
});
